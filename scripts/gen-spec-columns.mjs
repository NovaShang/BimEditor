#!/usr/bin/env node
/**
 * Regenerate editor/src/model/specColumns.generated.ts from the BimDown spec
 * (csv-schema yaml): per table, the columns stored in CSV and the fields
 * stored as GeoJSON Feature properties. Computed fields are in neither.
 *
 *   node scripts/gen-spec-columns.mjs [path/to/bimdown-spec/spec]
 *
 * Default spec path is the sibling submodule in the BimClaw monorepo.
 */
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const here = dirname(fileURLToPath(import.meta.url));
const specDir = resolve(process.argv[2] ?? join(here, '..', '..', 'bimdown-spec', 'spec'));
const out = join(here, '..', 'editor', 'src', 'model', 'specColumns.generated.ts');

export function specColumns(specDir) {
  const schemas = new Map();
  const walk = (dir) => {
    for (const entry of readdirSync(dir)) {
      const full = join(dir, entry);
      if (statSync(full).isDirectory()) walk(full);
      else if (entry.endsWith('.yaml')) {
        const raw = parse(readFileSync(full, 'utf-8'));
        if (raw?.name) schemas.set(raw.name, raw);
      }
    }
  };
  walk(join(specDir, 'csv-schema'));

  const resolved = new Map();
  const fieldsOf = (name) => {
    if (resolved.has(name)) return resolved.get(name);
    const schema = schemas.get(name);
    const fields = [];
    for (const base of schema.bases ?? []) {
      for (const f of fieldsOf(base)) if (!fields.some(x => x.name === f.name)) fields.push(f);
    }
    for (const f of schema.fields ?? []) {
      const i = fields.findIndex(x => x.name === f.name);
      if (i >= 0) fields[i] = f; else fields.push(f);
    }
    resolved.set(name, fields);
    return fields;
  };

  const tables = {};
  for (const name of [...schemas.keys()].sort()) {
    if (schemas.get(name).abstract) continue;
    const fields = fieldsOf(name).filter(f => !f.computed);
    tables[name] = {
      csv: fields.filter(f => (f.storage ?? 'csv') === 'csv').map(f => f.name),
      geojson: fields.filter(f => f.storage === 'geojson_property').map(f => f.name),
    };
  }
  return tables;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const tables = specColumns(specDir);
  const list = (a) => `[${a.map(x => `'${x}'`).join(', ')}]`;
  const body = `{\n${Object.entries(tables).map(([t, c]) => `  ${t}: { csv: ${list(c.csv)}, geojson: ${list(c.geojson)} },`).join('\n')}\n}`;
  writeFileSync(out, `// Generated by scripts/gen-spec-columns.mjs from bimdown-spec/spec/csv-schema. Do not edit.
// Per table: columns stored in CSV, and fields stored as GeoJSON Feature properties.

export const SPEC_COLUMNS: Record<string, { csv: string[]; geojson: string[] }> = ${body};
`);
  console.log(`wrote ${out} (${Object.keys(tables).length} tables)`);
}
